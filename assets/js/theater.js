function sceneRepresentatives(d){
  const reps=new Array(d.opts.length),used=new Set();
  d.opts.forEach((o,i)=>{
    if(o.show!==1)return;
    const c=candidateList(o)[0];
    if(c){reps[i]=c;used.add(c.type)}
  });
  d.opts.forEach((o,i)=>{
    if(reps[i])return;
    const list=candidateList(o);if(!list.length)return;
    const top=list[0].score;
    const tied=list.filter(c=>Math.abs(c.score-top)<1e-12);
    const chosen=tied.find(c=>!used.has(c.type))||list[0];
    reps[i]=chosen;used.add(chosen.type);
  });
  return reps;
}
function orderedCandidates(d,optionIndex){
  const list=candidateList(d.opts[optionIndex]);
  const rep=sceneRepresentatives(d)[optionIndex];
  if(!rep||!list.length)return list;
  const idx=list.findIndex(c=>c.type===rep.type);
  if(idx>0&&Math.abs(list[idx].score-list[0].score)<1e-12){
    const [chosen]=list.splice(idx,1);list.unshift(chosen);
  }
  return list;
}

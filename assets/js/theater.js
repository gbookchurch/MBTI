function clearerPastorModelNote(d,optionIndex){
  const o=d.opts[optionIndex],pairs=[['I','E'],['S','N'],['T','F'],['J','P']],sig=String(o.signal||'xxxx').padEnd(4,'x');
  const clear=[],uncertain=[];
  pairs.forEach(([a,b],idx)=>{
    const letter=sig[idx],av=o.axis[a],bv=o.axis[b];
    if(letter&&letter.toLowerCase()!=='x'){
      const other=letter===a?b:a;
      clear.push(`${letter} ${o.axis[letter]}（${AXIS_MEANING[letter]}）`);
    }else{
      uncertain.push(`${a} ${av} / ${b} ${bv}`);
    }
  });
  let note='';
  if(clear.length)note+=`比較明顯的是 ${clear.join('、')}。`;
  if(uncertain.length)note+=`${uncertain.join('、')} 比較接近，這一題不足以判定。`;
  const ranked=orderedCandidates(d,optionIndex);
  if(ranked.length>1){
    const vals=ranked.map(c=>c.score*100),tied=Math.max(...vals)-Math.min(...vals)<0.05;
    note+=tied
      ? `因此 ${ranked.map(c=>c.type).join('、')} 的模型符合度相同，全部保留。`
      : `因此目前保留 ${ranked.map(c=>c.type).join('、')} 這 ${ranked.length} 種可能。`;
  }else if(ranked.length===1)note+=`整體最接近 ${ranked[0].type}。`;
  return note;
}
